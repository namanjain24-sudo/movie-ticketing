import { useEventListener } from 'expo';
import { useVideoPlayer, VideoView } from 'expo-video';
import { useEffect, useState } from 'react';
import { Pressable, StyleSheet, View, type ViewStyle } from 'react-native';
import Ionicons from '@expo/vector-icons/Ionicons';
import { useReducedMotion } from 'react-native-reanimated';
import { Text } from '../../components/ui';
import type { Sponsor } from './sponsors';

/**
 * One sponsor film, playing in place.
 *
 * ## Why these are video at all
 *
 * The marketing site draws the same four ideas on a live canvas. React Native
 * has no canvas, so the choice here was a WebView each — a browser engine per
 * ad, for a card — or redrawing every film by hand in Reanimated and keeping
 * two of everything in step. An MP4 is around 300 KB, plays through one
 * surface for all four, and is the same picture on every device. The files
 * are generated by `scripts/render-ad-films.mjs` from a canvas that is a pure
 * function of time, so they can be regenerated rather than trusted.
 *
 * ## How it behaves
 *
 * Muted, looping, no audio track at all — an ad that makes noise in a list is
 * an ad somebody closes. It plays only while `active`, which the surrounding
 * screen sets from what is actually on screen: a film decoding behind four
 * screens of scroll is battery spent on a thing nobody is looking at.
 *
 * Under reduce-motion it does not play by itself. The still frame stays up
 * with a play control over it, so the person who asked the OS for fewer
 * moving things gets the choice rather than the motion.
 */
export function SponsorFilm({
  sponsor,
  active = true,
  style,
  rounded = 0,
}: {
  sponsor: Sponsor;
  active?: boolean;
  style?: ViewStyle;
  rounded?: number;
}) {
  const reducedMotion = useReducedMotion();

  const player = useVideoPlayer(sponsor.film, (p) => {
    p.loop = true;
    p.muted = true;
    // Never a volume duck on somebody's music: the files carry no audio
    // stream, and this makes sure nothing requests audio focus either.
    p.volume = 0;
  });

  // `null` until the player says otherwise — a frame drawn before the first
  // decoded frame is a black rectangle, and the overlay below covers it.
  const [ready, setReady] = useState(false);
  const [playing, setPlaying] = useState(false);

  useEventListener(player, 'statusChange', ({ status }) => {
    if (status === 'readyToPlay') setReady(true);
  });
  useEventListener(player, 'playingChange', ({ isPlaying }) => setPlaying(isPlaying));

  useEffect(() => {
    if (!active) {
      player.pause();
      return;
    }
    if (reducedMotion) return;
    player.play();
  }, [active, player, reducedMotion]);

  return (
    <View
      style={[
        {
          overflow: 'hidden',
          borderRadius: rounded,
          backgroundColor: '#0B0B10',
          aspectRatio: 16 / 9,
        },
        style,
      ]}
    >
      <VideoView
        player={player}
        style={{ width: '100%', height: '100%' }}
        contentFit="cover"
        // The app's own chrome says what this is and where it goes; the
        // platform's playback furniture on top of it would be a second,
        // contradictory set of controls on a nine second loop.
        nativeControls={false}
        fullscreenOptions={{ enable: false }}
        allowsPictureInPicture={false}
        accessibilityLabel={`${sponsor.name}: ${sponsor.kicker}. A house ad for a project by this app's author.`}
      />

      {/* The still-frame state: before the first frame is decoded, and
          whenever reduce-motion has stopped it playing by itself. */}
      {!ready || (!playing && reducedMotion) ? (
        <View
          style={[
            StyleSheet.absoluteFill,
            {
              alignItems: 'center',
              justifyContent: 'center',
              backgroundColor: ready ? 'rgba(11,11,16,0.35)' : '#0B0B10',
            },
          ]}
        >
          {ready ? (
            <Pressable
              accessibilityRole="button"
              accessibilityLabel={`Play the ${sponsor.name} film`}
              onPress={() => player.play()}
              style={{
                width: 44,
                height: 44,
                borderRadius: 22,
                alignItems: 'center',
                justifyContent: 'center',
                backgroundColor: 'rgba(0,0,0,0.55)',
                borderWidth: 1,
                borderColor: 'rgba(255,255,255,0.3)',
              }}
            >
              <Ionicons name="play" size={20} color="#FFFFFF" />
            </Pressable>
          ) : (
            // The film's own mark rather than the brand name: the card under
            // this already says the name, and a placeholder that repeats it
            // reads as the same words printed twice while the first frame
            // decodes.
            <View
              style={{
                width: 34,
                height: 34,
                borderRadius: 10,
                alignItems: 'center',
                justifyContent: 'center',
                backgroundColor: sponsor.accent,
                opacity: 0.85,
              }}
            >
              <Text variant="label" style={{ color: '#0B0B10' }}>
                {sponsor.name[0]}
              </Text>
            </View>
          )}
        </View>
      ) : null}
    </View>
  );
}
