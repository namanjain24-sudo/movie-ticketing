/**
 * The sponsor slots, and what is honest to say in them.
 *
 * A ticketing app has ad inventory — the space beside a film, the moment
 * after a booking confirms — and this one fills it with the author's own
 * projects rather than leaving a hole or pretending somebody paid for it.
 * Every slot is labelled a house ad, in the film itself and in the card
 * around it, because an app that argues for honest software must not open
 * with a lie about its own revenue.
 *
 * Each `film` is an MP4 rendered by `scripts/render-ad-films.mjs` from a
 * canvas that is a pure function of time, so the asset in the repo can be
 * regenerated byte for byte rather than taken on trust.
 *
 * Claims here are the ones each project's own page makes. Nothing in this
 * file is a feature somebody wished for.
 */
export interface Sponsor {
  id: string;
  name: string;
  /** Three or four words, under the name. */
  kicker: string;
  /** One sentence. What the thing is, not what it aspires to be. */
  blurb: string;
  film: VideoSource;
  /** Brand accent, for the card's own chrome. Matches the film's palette. */
  accent: string;
  /** Only where one actually exists and is public. */
  url?: string;
  /** Said in place of a link when there is nothing to open. */
  note: string;
}

