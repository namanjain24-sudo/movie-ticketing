export function sponsorById(id: string): Sponsor | undefined {
  return SPONSORS.find((s) => s.id === id);
}

/**
 * Which slot to show in a single-slot placement.
 *
 * Rotated by the day rather than at random, so the home screen does not
 * reshuffle under somebody's thumb every time a query refetches, and so two
 * people looking at the same phone on the same day see the same thing.
 */
export function sponsorOfTheDay(now: Date = new Date(), pool: Sponsor[] = SPONSORS): Sponsor {
  const days = Math.floor(now.getTime() / 86_400_000);
  return pool[((days % pool.length) + pool.length) % pool.length]!;
}
